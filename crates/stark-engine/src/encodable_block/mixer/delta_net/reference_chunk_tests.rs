fn upload<B: Backend, T: ArrayElement>(
    values: &[T],
    commands: &mut <B::CommandBuffer as CommandBuffer>::Encoding,
) -> B::ScratchBuffer {
    let source = commands.allocate_constant_from_slice(values).unwrap();
    let mut output = commands.allocate_scratch(std::mem::size_of_val(values)).unwrap();
    commands.encode_copy(&source, &mut output);
    output
}

fn source_golden<B: Backend>() {
    const ROWS: usize = 65;
    const WIDTH: usize = 128;
    const STRIDE: usize = WIDTH * 3;
    let context = B::Context::new().unwrap();
    let mut input = vec![bf16::ZERO; ROWS * STRIDE];
    for row in 0..ROWS {
        for channel in 0..WIDTH {
            input[row * STRIDE + channel] = bf16::from_f32(((row * 7 + channel * 3) % 31) as f32 / 16.0 - 15.0 / 16.0);
            input[row * STRIDE + WIDTH + channel] =
                bf16::from_f32(((row * 11 + channel * 5) % 37) as f32 / 16.0 - 18.0 / 16.0);
            input[row * STRIDE + 2 * WIDTH + channel] =
                bf16::from_f32(((row * 13 + channel * 7) % 41) as f32 / 16.0 - 20.0 / 16.0);
        }
    }
    let beta = (0..ROWS).map(|row| ((row % 7) + 1) as f32 / 8.0).collect::<Vec<_>>();
    let log_decay = (0..ROWS).map(|row| -(((row % 5) + 1) as f32) / 32.0).collect::<Vec<_>>();
    let initial = (0..WIDTH * WIDTH)
        .map(|index| {
            let dv = index / WIDTH;
            let dk = index % WIDTH;
            ((dk * 13 + dv * 7) % 29) as f32 / 512.0 - 14.0 / 512.0
        })
        .collect::<Vec<_>>();
    let mut state = create_buffer_with_data::<B, f32>(&context, &initial);
    let mut readback = create_buffer::<B, bf16>(&context, ROWS * WIDTH);
    let core = ReferenceChunk::<B>::new(&context).unwrap();
    let l2 = <B::Kernels as Kernels>::ReferenceGDNQKL2Kernel::new(&context).unwrap();
    let mut commands = context.create_command_buffer(None, None).unwrap();
    let input = upload::<B, _>(&input, &mut commands);
    let beta = upload::<B, _>(&beta, &mut commands);
    let log_decay = upload::<B, _>(&log_decay, &mut commands);
    let mut q = commands.allocate_scratch_for_shape(&[ROWS as u32, WIDTH as u32], DataType::F32).unwrap();
    let mut k = commands.allocate_scratch(q.size()).unwrap();
    let mut output = commands.allocate_scratch_for_shape(&[ROWS as u32, WIDTH as u32], DataType::BF16).unwrap();
    l2.encode(&input, &mut q, &mut k, WIDTH as u32, ROWS as u32, STRIDE as u32, &mut commands);
    core.encode(
        &q,
        &k,
        &beta,
        &log_decay,
        &input,
        &mut state,
        &mut output,
        ROWS as u32,
        1,
        1,
        WIDTH as u32,
        WIDTH as u32,
        STRIDE as u32,
        &mut commands,
    )
    .unwrap();
    commands.encode_copy(&output, &mut readback);
    commands.end_encoding().submit().wait_until_completed().unwrap();

    // Independently generated by pinned HF modeling_qwen3_5.py revision
    // 2e12b325d5c4532f3ec5b0ec54e1ff0b7e0db397, PyTorch 2.14.1 CPU eager,
    // eight threads. The source receives BF16 q/k/v/beta, F32 g and nonzero
    // initial state [Dk,Dv]; this test stores state as native [Dv,Dk].
    let output_bytes =
        buffer_to_vec::<B, bf16>(&readback).into_iter().flat_map(|v| v.to_bits().to_le_bytes()).collect::<Vec<_>>();
    let state_bytes = buffer_to_vec::<B, f32>(&state).into_iter().flat_map(|v| v.to_le_bytes()).collect::<Vec<_>>();
    assert_eq!(
        format!("{:x}", Sha256::digest(output_bytes)),
        "af11efd506a0ee4e6d0cc86d776d83ca4661eb17662a126e339c44639b7631a6"
    );
    assert_eq!(
        format!("{:x}", Sha256::digest(state_bytes)),
        "b2ac46655f66852b467bd839db56919f89144b4c525683e5cb0ce649fed22ee9"
    );
}

fn cumsum_f64_prefixes<B: Backend>() {
    const ROWS: usize = 257;
    const PADDED: usize = 320;
    let context = B::Context::new().unwrap();
    let mut seed = 0x3915_812bu32;
    let mut log_decay = (0..ROWS)
        .map(|_| {
            seed = seed.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
            f32::from_bits(0x8000_0000 | (seed & 0x7f7f_ffff))
        })
        .collect::<Vec<_>>();
    log_decay[..8].copy_from_slice(&[
        -1.0,
        -2f32.powi(-24),
        -2f32.powi(-54),
        -0.0,
        -f32::from_bits(1),
        -f32::MAX,
        -f32::MAX,
        -1.0,
    ]);
    let mut expected = Vec::with_capacity(PADDED);
    for chunk in 0..ROWS.div_ceil(64) {
        let mut sum = 0.0f64;
        for index in 0..64 {
            sum += f64::from(log_decay.get(chunk * 64 + index).copied().unwrap_or(0.0));
            expected.push(sum as f32);
        }
    }
    let q_input = create_buffer_with_data::<B, f32>(&context, &vec![0.0; ROWS * 128]);
    let beta = create_buffer_with_data::<B, f32>(&context, &vec![0.0; ROWS]);
    let decay = create_buffer_with_data::<B, f32>(&context, &log_decay);
    let values = create_buffer_with_data::<B, bf16>(&context, &vec![bf16::ZERO; ROWS * 384]);
    let mut q = create_buffer::<B, f32>(&context, PADDED * 128);
    let mut k = create_buffer::<B, f32>(&context, PADDED * 128);
    let mut kb = create_buffer::<B, f32>(&context, PADDED * 128);
    let mut vb = create_buffer::<B, f32>(&context, PADDED * 128);
    let mut cumulative = create_buffer::<B, f32>(&context, PADDED);
    let kernel = <B::Kernels as Kernels>::ReferenceGDNChunkPrepareKernel::new(&context).unwrap();
    let mut commands = context.create_command_buffer(None, None).unwrap();
    kernel.encode(
        &q_input,
        &q_input,
        &beta,
        &decay,
        &values,
        &mut q,
        &mut k,
        &mut kb,
        &mut vb,
        &mut cumulative,
        ROWS as u32,
        1,
        1,
        128,
        128,
        384,
        &mut commands,
    );
    commands.end_encoding().submit().wait_until_completed().unwrap();
    let actual = buffer_to_vec::<B, f32>(&cumulative);
    assert!(actual.iter().zip(expected).all(|(a, e)| a.to_bits() == e.to_bits()));
}

